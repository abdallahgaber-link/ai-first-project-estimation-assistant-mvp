                  ),
                ),
              )).toList(),
            ),
          )).toList(),
        ],
      ),
    );
  }

  Widget _buildRisksTab(BuildContext context) {
    return SingleChildScrollView(
      padding: ResponsiveUtils.getResponsivePadding(context),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            'Project Risks',
            style: TextStyle(
              fontSize: ResponsiveUtils.getResponsiveFontSize(context, 18),
              fontWeight: FontWeight.bold,
            ),
          ),
          SizedBox(height: ResponsiveUtils.getResponsiveSpacing(context)),
          ...estimation.risks.map((risk) => Card(
            margin: EdgeInsets.only(bottom: 8.h),
            child: ListTile(
              leading: _buildRiskSeverityBadge(_categorizeRiskSeverity(risk)),
              title: Text(
                risk,
                style: TextStyle(
                  fontSize: ResponsiveUtils.getResponsiveFontSize(context, 13),
                ),
              ),
            ),
          )).toList(),
        ],
      ),
    );
  }

  Widget _buildCalibrationTab(BuildContext context) {
    return SingleChildScrollView(
      padding: ResponsiveUtils.getResponsivePadding(context),
      child: CalibrationPanel(
        originalEstimation: estimation,
        onEstimationChanged: (newEstimation) {
          // Update the current estimation state
          // This will trigger UI updates in other tabs
        },
      ),
    );
  }

  Widget _buildRiskSeverityBadge(String severity) {
    Color color;
    IconData icon;
    
    switch (severity.toLowerCase()) {
      case 'high':
        color = Colors.red;
        icon = Icons.error;
        break;
      case 'medium':
        color = Colors.orange;
        icon = Icons.warning;
        break;
      default:
        color = Colors.green;
        icon = Icons.info;
    }

    return Container(
      padding: EdgeInsets.symmetric(horizontal: 8.w, vertical: 4.h),
      decoration: BoxDecoration(
        color: color.withOpacity(0.1),
        borderRadius: BorderRadius.circular(12.r),
        border: Border.all(color: color.withOpacity(0.3)),
      ),
      child: Row(
        mainAxisSize: MainAxisSize.min,
        children: [
          Icon(icon, size: 12.sp, color: color),
          SizedBox(width: 4.w),
          Text(
            severity.toUpperCase(),
            style: TextStyle(
              fontSize: 10.sp,
              color: color,
              fontWeight: FontWeight.w500,
            ),
          ),
        ],
      ),
    );
  }

  String _categorizeRiskSeverity(String risk) {
    final riskLower = risk.toLowerCase();
    
    // High severity keywords
    if (riskLower.contains('security') ||
        riskLower.contains('data loss') ||
        riskLower.contains('critical') ||
        riskLower.contains('failure') ||
        riskLower.contains('breach')) {
      return 'High';
    }
    
    // Medium severity keywords
    if (riskLower.contains('performance') ||
        riskLower.contains('delay') ||
        riskLower.contains('integration') ||
        riskLower.contains('compatibility')) {
      return 'Medium';
    }
    
    return 'Low';
  }

  void _showModuleExplanation(BuildContext context, ModuleEstimate module) {
    showDialog(
      context: context,
      builder: (context) => ModuleExplanationDialog(module: module),
    );
  }
}
