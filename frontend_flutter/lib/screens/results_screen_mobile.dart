import 'package:flutter/material.dart';
import 'package:flutter_hooks/flutter_hooks.dart';
import 'package:hooks_riverpod/hooks_riverpod.dart';
import 'package:flutter_screenutil/flutter_screenutil.dart';
import '../models/estimation_response.dart';
import '../services/api_service.dart';
import '../widgets/module_explanation_dialog.dart';
import '../widgets/calibration_panel.dart';
import '../utils/responsive_utils.dart';

class ResultsScreenMobile extends HookConsumerWidget {
  final EstimationResponse estimation;
  final EstimationMeta meta;
  final String projectTitle;

  const ResultsScreenMobile({
    super.key,
    required this.estimation,
    required this.meta,
    required this.projectTitle,
  });

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final selectedTabIndex = useState<int>(0);
    final isExporting = useState(false);
    final currentEstimation = useState<EstimationResponse>(estimation);

    Future<void> exportEstimation(String format) async {
      isExporting.value = true;
      try {
        await ApiService.exportEstimation(estimation, projectTitle, format);
        if (context.mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('Exported as $format successfully')),
          );
        }
      } catch (e) {
        if (context.mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('Export failed: ${e.toString()}')),
          );
        }
      } finally {
        isExporting.value = false;
      }
    }

    return Scaffold(
      appBar: AppBar(
        title: Text(
          projectTitle,
          style: TextStyle(
            fontSize: ResponsiveUtils.isMobile(context) ? 16.sp : 18.sp,
            color: Colors.white,
            fontWeight: FontWeight.w600,
          ),
        ),
        backgroundColor: Colors.blue[800],
        foregroundColor: Colors.white,
        elevation: 4,
        actions: [
          Container(
            margin: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
            decoration: BoxDecoration(
              gradient: LinearGradient(
                colors: [Colors.green.shade400, Colors.green.shade600],
                begin: Alignment.topLeft,
                end: Alignment.bottomRight,
              ),
              borderRadius: BorderRadius.circular(12),
              boxShadow: [
                BoxShadow(
                  color: Colors.green.withOpacity(0.3),
                  blurRadius: 4,
                  offset: const Offset(0, 2),
                ),
              ],
            ),
            child: PopupMenuButton<String>(
              icon: const Icon(Icons.download, color: Colors.white),
              tooltip: 'Export',
              onSelected: (format) => exportEstimation(format),
              itemBuilder: (context) => [
                PopupMenuItem(
                  value: 'csv',
                  child: Row(
                    children: [
                      Icon(Icons.table_chart, color: Colors.green[700]),
                      const SizedBox(width: 8),
                      const Text('Export CSV'),
                    ],
                  ),
                ),
                PopupMenuItem(
                  value: 'xlsx',
                  child: Row(
                    children: [
                      Icon(Icons.grid_on, color: Colors.green[700]),
                      const SizedBox(width: 8),
                      const Text('Export Excel'),
                    ],
                  ),
                ),
                PopupMenuItem(
                  value: 'pdf',
                  child: Row(
                    children: [
                      Icon(Icons.picture_as_pdf, color: Colors.green[700]),
                      const SizedBox(width: 8),
                      const Text('Export PDF'),
                    ],
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
      body: Column(
        children: [
          // Provider info header - responsive
          Container(
            width: double.infinity,
            padding: ResponsiveUtils.getResponsivePadding(context),
            decoration: BoxDecoration(
              color: Colors.grey[100],
              border: Border(
                bottom: BorderSide(color: Colors.grey[300]!),
              ),
            ),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Row(
                  children: [
                    Icon(Icons.smart_toy, color: Colors.blue[700]),
                    SizedBox(width: 8.w),
                    Expanded(
                      child: Text(
                        'Generated by ${meta.provider}',
                        style: Theme.of(context).textTheme.titleMedium?.copyWith(
                          fontWeight: FontWeight.bold,
                          fontSize: ResponsiveUtils.getResponsiveFontSize(context, 16),
                        ),
                      ),
                    ),
                  ],
                ),
                SizedBox(height: ResponsiveUtils.getResponsiveSpacing(context) / 2),
                Wrap(
                  spacing: ResponsiveUtils.isMobile(context) ? 8.0 : 12.0,
                  runSpacing: ResponsiveUtils.isMobile(context) ? 6.0 : 8.0,
                  children: [
                    _buildInfoChip('Model', meta.model, Icons.memory),
                    _buildInfoChip('Tokens', '${meta.totalTokens}', Icons.token),
                    _buildInfoChip('Latency', '${meta.latencyMs}ms', Icons.speed),
                    if (meta.retryCount > 0)
                      _buildInfoChip('Retries', '${meta.retryCount}', Icons.refresh),
                  ],
                ),
              ],
            ),
          ),

          // Summary cards - responsive
          Container(
            padding: ResponsiveUtils.getResponsivePadding(context),
            child: Column(
              children: [
                // Main metrics row
                Row(
                  children: [
                    Expanded(
                      child: _buildSummaryCard(
                        'Total Cost',
                        '${currentEstimation.value.totals.totalMDs.toStringAsFixed(1)} MD',
                        Colors.green,
                        Icons.attach_money,
                      ),
                    ),
                    SizedBox(width: 8.w),
                    Expanded(
                      child: _buildSummaryCard(
                        'Duration',
                        '${(currentEstimation.value.totals.totalMDs / 5).toStringAsFixed(1)} weeks',
                        Colors.orange,
                        Icons.schedule,
                      ),
                    ),
                  ],
                ),
                SizedBox(height: 12.h),
                // Additional metrics row
                Row(
                  children: [
                    Expanded(
                      child: _buildSummaryCard(
                        'Total Effort',
                        '${currentEstimation.value.totals.developmentMDs.toStringAsFixed(1)} MD',
                        Colors.purple,
                        Icons.work,
                      ),
                    ),
                    SizedBox(width: 8.w),
                    Expanded(
                      child: _buildSummaryCard(
                        'Buffer Used',
                        '${(estimation.bufferUsed * 100).toStringAsFixed(0)}%',
                        Colors.red,
                        Icons.security,
                      ),
                    ),
                  ],
                ),
                SizedBox(height: 12.h),
                // Effort breakdown cards
                Row(
                  children: [
                    Expanded(
                      child: _buildSummaryCard(
                        'Development',
                        '${(estimation.totals.developmentMDs * 0.7).toStringAsFixed(1)} MD',
                        Colors.blue,
                        Icons.code,
                      ),
                    ),
                    SizedBox(width: 8.w),
                    Expanded(
                      child: _buildSummaryCard(
                        'Testing',
                        '${(estimation.totals.developmentMDs * 0.15).toStringAsFixed(1)} MD',
                        Colors.teal,
                        Icons.bug_report,
                      ),
                    ),
                  ],
                ),
              ],
            ),
          ),

          // Tab navigation - mobile optimized
          Container(
            padding: EdgeInsets.symmetric(horizontal: 8.w),
            child: SingleChildScrollView(
              scrollDirection: Axis.horizontal,
              child: Row(
                children: [
                  _buildTabButton('Modules', Icons.view_module, 0, selectedTabIndex),
                  _buildTabButton('Roles', Icons.people, 1, selectedTabIndex),
                  _buildTabButton('WBS', Icons.account_tree, 2, selectedTabIndex),
                  _buildTabButton('Risks', Icons.warning, 3, selectedTabIndex),
                  _buildTabButton('Calibrate', Icons.tune, 4, selectedTabIndex),
                ],
              ),
            ),
          ),

          // Tab content
          Expanded(
            child: SingleChildScrollView(
              padding: EdgeInsets.all(8.w),
              child: IndexedStack(
                index: selectedTabIndex.value,
                children: [
                  _buildModulesTab(context),
                  _buildRolesTab(context),
                  _buildWBSTab(context),
                  _buildRisksTab(context),
                  _buildCalibrationTab(context),
                ],
              ),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildInfoChip(String label, String value, IconData icon) {
    return Container(
      padding: EdgeInsets.symmetric(horizontal: 8.w, vertical: 4.h),
      decoration: BoxDecoration(
        color: Colors.blue[50],
        borderRadius: BorderRadius.circular(12.r),
        border: Border.all(color: Colors.blue[200]!),
      ),
      child: Row(
        mainAxisSize: MainAxisSize.min,
        children: [
          Icon(icon, size: 14.sp, color: Colors.blue[700]),
          SizedBox(width: 4.w),
          Text(
            '$label: $value',
            style: TextStyle(
              fontSize: 11.sp,
              color: Colors.blue[700],
              fontWeight: FontWeight.w500,
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildSummaryCard(String title, String value, Color color, IconData icon) {
    return Card(
      child: Container(
        padding: EdgeInsets.all(12.w),
        child: Column(
          children: [
            Icon(icon, color: color, size: 24.sp),
            SizedBox(height: 8.h),
            Text(
              value,
              style: TextStyle(
                fontSize: 16.sp,
                fontWeight: FontWeight.bold,
                color: color,
              ),
            ),
            SizedBox(height: 4.h),
            Text(
              title,
              style: TextStyle(
                fontSize: 12.sp,
                color: Colors.grey[600],
              ),
              textAlign: TextAlign.center,
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildTabButton(String title, IconData icon, int index, ValueNotifier<int> selectedTabIndex) {
    final isSelected = selectedTabIndex.value == index;
    return Padding(
      padding: EdgeInsets.symmetric(horizontal: 4.w),
      child: GestureDetector(
        onTap: () => selectedTabIndex.value = index,
        child: Container(
          padding: EdgeInsets.symmetric(horizontal: 12.w, vertical: 8.h),
          decoration: BoxDecoration(
            color: isSelected ? Colors.blue[700] : Colors.transparent,
            borderRadius: BorderRadius.circular(20.r),
          ),
          child: Row(
            mainAxisSize: MainAxisSize.min,
            children: [
              Icon(
                icon,
                size: 16.sp,
                color: isSelected ? Colors.white : Colors.grey[600],
              ),
              SizedBox(width: 4.w),
              Text(
                title,
                style: TextStyle(
                  fontSize: 12.sp,
                  color: isSelected ? Colors.white : Colors.grey[600],
                  fontWeight: isSelected ? FontWeight.w600 : FontWeight.normal,
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildModulesTab(BuildContext context) {
    return SingleChildScrollView(
      padding: ResponsiveUtils.getResponsivePadding(context),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            'Project Modules',
            style: TextStyle(
              fontSize: ResponsiveUtils.getResponsiveFontSize(context, 18),
              fontWeight: FontWeight.bold,
            ),
          ),
          SizedBox(height: ResponsiveUtils.getResponsiveSpacing(context)),
          ...estimation.modules.map((module) => Card(
            margin: EdgeInsets.only(bottom: 8.h),
            child: ListTile(
              title: Text(
                module.name,
                style: TextStyle(
                  fontSize: ResponsiveUtils.getResponsiveFontSize(context, 14),
                  fontWeight: FontWeight.w600,
                ),
              ),
              subtitle: Text(
                '${module.weeks.toStringAsFixed(1)} weeks • ${module.complexity}',
                style: TextStyle(
                  fontSize: ResponsiveUtils.getResponsiveFontSize(context, 12),
                ),
              ),
              trailing: Row(
                mainAxisSize: MainAxisSize.min,
                children: [
                  Text(
                    '${module.totalPoints} pts',
                    style: TextStyle(
                      fontSize: ResponsiveUtils.getResponsiveFontSize(context, 14),
                      fontWeight: FontWeight.bold,
                      color: Colors.green[700],
                    ),
                  ),
                  SizedBox(width: 8.w),
                  IconButton(
                    icon: const Icon(Icons.info_outline),
                    onPressed: () => _showModuleExplanation(context, module),
                  ),
                ],
              ),
            ),
          )).toList(),
        ],
      ),
    );
  }

  Widget _buildRolesTab(BuildContext context) {
    return SingleChildScrollView(
      padding: ResponsiveUtils.getResponsivePadding(context),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            'Team Roles',
            style: TextStyle(
              fontSize: ResponsiveUtils.getResponsiveFontSize(context, 18),
              fontWeight: FontWeight.bold,
            ),
          ),
          SizedBox(height: ResponsiveUtils.getResponsiveSpacing(context)),
          ...estimation.roles.map((role) => Card(
            margin: EdgeInsets.only(bottom: 8.h),
            child: ListTile(
              leading: CircleAvatar(
                backgroundColor: Colors.blue[100],
                child: Icon(Icons.person, color: Colors.blue[700]),
              ),
              title: Text(
                role.role,
                style: TextStyle(
                  fontSize: ResponsiveUtils.getResponsiveFontSize(context, 14),
                  fontWeight: FontWeight.w600,
                ),
              ),
              subtitle: Text(
                '${role.effortWeeks.toStringAsFixed(1)} weeks',
                style: TextStyle(
                  fontSize: ResponsiveUtils.getResponsiveFontSize(context, 12),
                ),
              ),
              trailing: Text(
                '${role.percentage.toStringAsFixed(1)}%',
                style: TextStyle(
                  fontSize: ResponsiveUtils.getResponsiveFontSize(context, 14),
